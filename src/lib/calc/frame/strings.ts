/**
 * The words of the plane frame calculator's FORM AND TABLES, in English and in
 * Spanish (/resources/plane-frame-analysis; the page's own text, its hero and its notes, is
 * page-strings.ts).
 *
 * The tool (FrameCalculator.tsx) takes two sets of words. `t`, a part of the
 * first calculator's (beam/strings.ts, `ui`): what one calculator says as the
 * next does - how a number is written, the row of actions, "Remove", "Results",
 * the shape table's lines. And `w`, this file: everything that is about a
 * frame. A phrase the first calculator already has is taken from `t`, never
 * written again here (frame-strings.test.ts compares this file with the other
 * calculators' words, six words at a time).
 *
 * NOT EVERY WORD OF THE FIRST CALCULATOR IS THIS PAGE'S TO BORROW. Its
 * sentences say "beam", and a frame's page says "frame". `FrameShared` is the
 * list of what IS borrowed, and `sharedWords` picks exactly that out of the
 * first calculator's set, so that the server view hands the tool those words
 * and no others (what a server view hands a client component travels with
 * the page).
 *
 * NO WORDS IN THE LIBRARY. analysis.ts gives CODES (a problem, a warning, a
 * kind of support) and the numbers a sentence needs; the sentence is written
 * here, once per code, in both languages. A sentence with a number in it has
 * a hole for it: `{count}`. A hole can carry a plural: `{count|member|members}`
 * is the first word when the count is 1 and the second otherwise (text.ts
 * fills them).
 *
 * NO VERDICT, NO CODE. The page gives moments, shears, axial forces,
 * reactions and displacements: analysis numbers. No word here says whether a
 * member or a section will do, none names a standard, none speaks of a
 * factor or a capacity; the one line that says there is no design check is
 * `results.method`, which also says what the analysis assumes. Typical
 * section values are always called typical.
 *
 * Spanish as the other calculators write it - formal "usted" - and, for what
 * is a frame's: "pórtico", "nudo", "barra", "empotramiento", "apoyo
 * articulado", "apoyo de rodillo", "rótula", "momento flector", "fuerza
 * cortante", "fuerza axial", "reacciones", "deformada", "carga distribuida",
 * "carga trapezoidal", "asentamiento", "resorte", "luz" for the span, and
 * "tracción" and "compresión" for the two signs of an axial force. The minus
 * of a value is a true one.
 */

/** What this tool borrows of the first calculator's words: the pieces that say the same thing on any calculator. Its shape is `BeamUi`'s, so the whole of that set can be handed in where this is asked for. */
export type FrameShared = {
  numbers: BeamUi['numbers'];
  sheet: Pick<BeamUi['sheet'], 'locale' | 'printed'>;
  toolbar: Pick<BeamUi['toolbar'], 'units' | 'reset' | 'copied' | 'copyFailed' | 'print'>;
  supports: Pick<BeamUi['supports'], 'title'>;
  section: Pick<BeamUi['section'], 'title' | 'material' | 'E' | 'optional' | 'shape' | 'filter' | 'filterHint' | 'loading' | 'loadFailed' | 'reload' | 'noMatch'> & { materials: Pick<BeamUi['section']['materials'], 'steel' | 'aluminum' | 'custom'> };
  row: Pick<BeamUi['row'], 'remove'>;
  results: Pick<BeamUi['results'], 'title' | 'reactions' | 'support' | 'privacy' | 'upward' | 'downward'>;
};
/** The name the page's view and the tool's props know it by. */
export type SharedWords = FrameShared;

/** Exactly those words, out of the first calculator's set: what the server view hands the tool as `t`. */
export function sharedWords(ui: BeamUi): FrameShared {
  const { numbers } = ui;
  const { locale, printed } = ui.sheet;
  const { units, reset, copied, copyFailed, print } = ui.toolbar;
  const { title, material, E, optional, materials, shape, filter, filterHint, loading, loadFailed, reload, noMatch } = ui.section;
  const r = ui.results;
  return {
    numbers,
    sheet: { locale, printed },
    toolbar: { units, reset, copied, copyFailed, print },
    supports: { title: ui.supports.title },
    section: { title, material, E, optional, shape, filter, filterHint, loading, loadFailed, reload, noMatch, materials: { steel: materials.steel, aluminum: materials.aluminum, custom: materials.custom } },
    row: { remove: ui.row.remove },
    results: { title: r.title, reactions: r.reactions, support: r.support, privacy: r.privacy, upward: r.upward, downward: r.downward },
  };
}

