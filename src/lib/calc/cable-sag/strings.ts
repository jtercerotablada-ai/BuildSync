/**
 * The words of the cable calculator's FORM AND TABLES, in English and in
 * Spanish (/resources/cable-sag; the page's own text — its hero, its notes —
 * is page-strings.ts).
 *
 * The tool (CableSagCalculator.tsx) takes two sets of words. `t`, a part of
 * the first calculator's (beam/strings.ts, `ui`): what one calculator says as
 * the next does — how a number is written, the row of actions, "Remove",
 * "Results". And `w`, this file: everything that is about a cable. A phrase
 * the first calculator already has is taken from `t`, never written again here
 * (cable-sag-calculator.test.ts compares this file with the other calculators'
 * words, six words at a time).
 *
 * NOT EVERY WORD OF THE FIRST CALCULATOR IS THIS PAGE'S TO BORROW. Its
 * sentences say "beam", and a cable's page says "cable". `CableSagShared` is
 * the list of what IS borrowed, and `sharedWords` picks exactly that out of the
 * first calculator's set, so that the server view hands the tool those words
 * and no others.
 *
 * NO WORDS IN THE LIBRARY. analysis.ts gives CODES and the numbers a sentence
 * needs; the sentence is written here, once per code, in both languages. A
 * sentence with a number in it has a hole for it: `{count}`. A hole can carry
 * a plural: `{count|load|loads}` is the first word when the count is 1 and the
 * second otherwise. (text.ts fills them.)
 *
 * NO VERDICT, NO CODE. The page gives tensions, sags, lengths and angles. No
 * word here says whether a cable will do, none names a standard, none speaks of
 * a factor or a capacity — except the one line that says there is no check
 * (`results.note`), which also says the material values are typical.
 *
 * Spanish as the other calculators write it — formal "usted" — and, for what is
 * a cable's: "cable", "flecha" for the sag, "pretensión" and "tensión
 * horizontal", "catenaria" and "parábola", "cambio de estado", "luz" for the
 * span (never "vano" beside it, as on the truss and the other calculators),
 * "apoyo", "cargas puntuales" and "polígono funicular".
 */

/** What this tool borrows of the first calculator's words: the pieces that say the same thing on any calculator. Its shape is `BeamUi`'s, so the whole of that set can be handed in where this is asked for. */
export type CableSagShared = {
  numbers: BeamUi['numbers'];
  sheet: Pick<BeamUi['sheet'], 'locale' | 'printed'>;
  toolbar: Pick<BeamUi['toolbar'], 'units' | 'reset' | 'copied' | 'copyFailed' | 'print'>;
  section: Pick<BeamUi['section'], 'title' | 'optional'>;
  row: Pick<BeamUi['row'], 'remove'>;
  results: Pick<BeamUi['results'], 'title' | 'privacy' | 'upward' | 'downward'>;
};
/** The name the page's view and the tool's props know it by. */
export type SharedWords = CableSagShared;

/** Exactly those words, out of the first calculator's set: what the server view hands the tool as `t`. */
export function sharedWords(ui: BeamUi): CableSagShared {
  const { numbers } = ui;
  const { locale, printed } = ui.sheet;
  const { units, reset, copied, copyFailed, print } = ui.toolbar;
  const { title, optional } = ui.section;
  const r = ui.results;
  return {
    numbers,
    sheet: { locale, printed },
    toolbar: { units, reset, copied, copyFailed, print },
    section: { title, optional },
    row: { remove: ui.row.remove },
    results: { title: r.title, privacy: r.privacy, upward: r.upward, downward: r.downward },
  };
}

