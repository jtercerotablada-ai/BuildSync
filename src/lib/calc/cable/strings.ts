/**
 * The words of the cable calculator's FORM AND TABLES, in English and in
 * Spanish (/resources/cable; the page's own text - its hero, its notes - is
 * page-strings.ts).
 *
 * The tool (CableCalculator.tsx) takes two sets of words, as the truss and the
 * shaft do. `t`, a part of the first calculator's (beam/strings.ts, `ui`): what
 * one calculator says as the next does - how a number is written, the row of
 * actions, "Results", "optional". And `w`, this file: everything that is about
 * a cable. A phrase the first calculator already has is taken from `t`, never
 * written again here (cable-calculator.test.ts compares this file with the other
 * calculators' words, six words at a time). `CableShared` is the list of what IS
 * borrowed, and `sharedWords` picks exactly that out of the first calculator's
 * set, so that the server view hands the tool those words and no others.
 *
 * NO WORDS IN THE LIBRARY. analysis.ts gives CODES and the numbers a sentence
 * needs; the sentence is written here, once per code, in both languages. A hole
 * is `{count}`; with a plural, `{count|way|ways}` is the first word when the
 * count is 1 and the second otherwise (text.ts fills them).
 *
 * NO VERDICT, NO CODE. The page gives tensions, stresses, stretches, the ratio
 * of a breaking force to a tension, and the breaking force or the size that a
 * design factor or an allowable stress asks for. It says once, in `notes.noVerdict`,
 * that these are numbers only; no other sentence says whether a cable will do,
 * and none names a standard.
 *
 * THE CABLE'S NUMBERS ARE TYPICAL. The rope and strand values are typical ones
 * for a first estimate: the manufacturer's give the metallic area, the breaking
 * force and the modulus of the rope bought. A wire rope's EFFECTIVE modulus is
 * about half of steel's, and the page says so in plain words (`section.ropeModulus`).
 *
 * Spanish as an engineer in Latin America writes it, formal "usted": "cable",
 * "eslinga" (a two-leg sling), "tensión" (the force in the cable), "esfuerzo"
 * (the stress), "alargamiento", "deformación unitaria", "carga de rotura mínima",
 * "fricción" (never "rozamiento" beside it), "tambor" and "cabrestante" for the
 * capstan relation, "ángulo de envolvimiento" for the wrap.
 */

/** What this tool borrows of the first calculator's words: the pieces that say the same thing on any calculator. */
export type CableShared = {
  numbers: BeamUi['numbers'];
  sheet: Pick<BeamUi['sheet'], 'locale' | 'printed'>;
  toolbar: Pick<BeamUi['toolbar'], 'units' | 'reset' | 'copied' | 'copyFailed' | 'print'>;
  section: Pick<BeamUi['section'], 'optional'>;
  results: Pick<BeamUi['results'], 'title' | 'privacy'>;
};
/** The name the page's view and the tool's props know it by. */
export type SharedWords = CableShared;

/** Exactly those words, out of the first calculator's set: what the server view hands the tool as `t`. */
export function sharedWords(ui: BeamUi): CableShared {
  const { numbers } = ui;
  const { locale, printed } = ui.sheet;
  const { units, reset, copied, copyFailed, print } = ui.toolbar;
  return {
    numbers,
    sheet: { locale, printed },
    toolbar: { units, reset, copied, copyFailed, print },
    section: { optional: ui.section.optional },
    results: { title: ui.results.title, privacy: ui.results.privacy },
  };
}

