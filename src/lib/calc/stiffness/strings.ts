/**
 * The words of the stiffness matrix calculator's FORM, STEPS AND TABLES, in English and in Spanish ("Stiffness matrix, step by
 * step", the ninth calculator; the page's own text, its hero and its notes, is page-strings.ts).
 *
 * The tool (components/ttc/calc/stiffness/StiffnessCalculator.tsx) takes two sets of words. `t`, a part of the first calculator's
 * (beam/strings.ts, `ui`): what one calculator says as the next does - how a number is written, the row of actions, "Remove",
 * "Results", the shape table's lines. And `w`, this file: everything that is about a worked stiffness solution. A phrase the first
 * calculator already has is taken from `t`, never written again here. `sharedWords` picks exactly the pieces that are borrowed out
 * of the first calculator's set, so that the server view hands the tool those words and no others (what a server view hands a
 * client component travels with the page).
 *
 * NO WORDS IN THE LIBRARY. analysis.ts gives CODES (a problem, a warning, a step, a reason a cell is marked) and the numbers a
 * sentence needs; the sentence is written here, once per code, in both languages. A hole is `{count}`; it can carry a plural:
 * `{count|member|members}` is the first word when the count is 1 and the second otherwise (text.ts fills them). A sentence may
 * hold math in the lib's alphabet - `K_FF`, `u_F`, `T^T` - which the page sets as a subscript or a superscript (notation.ts).
 *
 * NO VERDICT, NO CODE. The page gives stiffnesses, displacements, reactions and member forces: analysis numbers. No word here says
 * whether a member or a section will do, none names a standard, none speaks of a factor or a capacity; the one line that says
 * there is no design check, and what the analysis assumes, is `results.method`.
 *
 * Spanish as the other calculators write it - formal "usted" - and, for what is this tool's: "matriz de rigidez", "grados de
 * libertad", "ensamblaje", "vector de cargas", "partición", "eliminación de Gauss", "sustitución hacia atrás", "reacciones",
 * "fuerzas en los extremos", "matriz de transformación", "cosenos directores", "barra", "nudo", "cercha", "pórtico" and
 * "empotramiento". The minus of a value is a true one.
 */

/** What this tool borrows of the first calculator's words: the pieces that say the same thing on any calculator. Its shape is `BeamUi`'s, so the whole of that set can be handed in where this is asked for. */
export type StiffnessShared = {
  numbers: BeamUi['numbers'];
  sheet: Pick<BeamUi['sheet'], 'locale' | 'printed'>;
  toolbar: Pick<BeamUi['toolbar'], 'units' | 'reset' | 'copied' | 'copyFailed' | 'print'>;
  supports: Pick<BeamUi['supports'], 'title'>;
  section: Pick<BeamUi['section'], 'title' | 'material' | 'E' | 'optional' | 'shape' | 'filter' | 'filterHint' | 'loading' | 'loadFailed' | 'reload' | 'noMatch'> & { materials: Pick<BeamUi['section']['materials'], 'steel' | 'aluminum' | 'custom'> };
  row: Pick<BeamUi['row'], 'remove'>;
  results: Pick<BeamUi['results'], 'title' | 'privacy'>;
};
/** The name the page's view and the tool's props know it by. */
export type SharedWords = StiffnessShared;

/** Exactly those words, out of the first calculator's set: what the server view hands the tool as `t`. */
export function sharedWords(ui: BeamUi): StiffnessShared {
  const { numbers } = ui;
  const { locale, printed } = ui.sheet;
  const { units, reset, copied, copyFailed, print } = ui.toolbar;
  const { title, material, E, optional, materials, shape, filter, filterHint, loading, loadFailed, reload, noMatch } = ui.section;
  const r = ui.results;
  return {
    numbers,
    sheet: { locale, printed },
    toolbar: { units, reset, copied, copyFailed, print },
    supports: { title: ui.supports.title },
    section: { title, material, E, optional, shape, filter, filterHint, loading, loadFailed, reload, noMatch, materials: { steel: materials.steel, aluminum: materials.aluminum, custom: materials.custom } },
    row: { remove: ui.row.remove },
    results: { title: r.title, privacy: r.privacy },
  };
}

